"""dataset/dataset_config.json must stay in sync with the folder tree.

It is generated by scripts/build_dataset_config.py from dataset/<class>/<session>/
plus each session's session.json. A hand-edit or a forgotten regenerate after
adding a session silently trains on the wrong split.
"""

import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BUILDER = ROOT / "scripts" / "build_dataset_config.py"
CONFIG = ROOT / "dataset" / "dataset_config.json"


class DatasetConfig(unittest.TestCase):
    def test_config_matches_builder_output(self):
        result = subprocess.run(
            [sys.executable, str(BUILDER), "--check"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(
            result.returncode,
            0,
            f"dataset_config.json is stale -- run scripts/build_dataset_config.py\n{result.stderr}",
        )

    def test_every_session_has_the_nine_files_and_a_class(self):
        config = json.loads(CONFIG.read_text(encoding="utf-8"))
        classes = ("correct", "incomplete_range", "elbow_movement")
        for entry in config["sessions"]:
            self.assertEqual(entry["label"], classes[entry["class_id"]])
            folder = ROOT / "dataset" / entry["folder"]
            n = int(entry["session"])
            for node in (2, 3, 4):
                for sensor in ("BNO85", "ICM45686"):
                    self.assertTrue(
                        (folder / f"R{n:04d}N{node}_{sensor}.csv").is_file(),
                        f"missing R{n:04d}N{node}_{sensor}.csv in {entry['folder']}",
                    )
                self.assertTrue((folder / f"R{n:04d}N{node}_metadata.json").is_file())

    def test_folds_never_share_a_session(self):
        config = json.loads(CONFIG.read_text(encoding="utf-8"))
        held_out = set(config.get("held_out_sessions", []))
        for fold in config.get("validation_folds", []):
            train, test = set(fold["train_sessions"]), set(fold["test_sessions"])
            self.assertEqual(train & test, set(), f"fold {fold['name']} shares sessions")
            self.assertEqual(test & held_out, set(), "held-out session appears in a CV fold")
        for fold in config.get("lowo_folds", []):
            self.assertEqual(set(fold["train_sessions"]) & set(fold["test_sessions"]), set())


if __name__ == "__main__":
    unittest.main()
